function framesToShowLeds(frame){
  return frame.map(r=>r.split("").join(" ")).join("\n");
}
function funcNameFromId(id){
  const parts = id.split(/[-_ ]+/);
  return parts.map(p=>p.charAt(0).toUpperCase()+p.slice(1)).join("");
}
function generateMicrobitFunction(anim, opts={}){
  const fn = funcNameFromId(anim.id);
  const pause = opts.pause ?? anim.speed ?? 300;
  const mode = opts.mode ?? "infinite"; // infinite | repeat4 | once
  const lines = [];
  lines.push(`function ${fn}() {`);
  const emitFrame = (f)=>{
    lines.push(`    basic.showLeds(`+"`");
    lines.push(`            ${framesToShowLeds(f).split("\n").join("\n            ")}`.replace(/\s+$/,""));
    lines.push(`            `+"`)");
    lines.push(`    basic.pause(${pause})`);
  };
  if(mode==="infinite"){
    lines.push(`    while (true) {`);
    anim.frames.forEach(f=>{
      lines.push(`        basic.showLeds(`+"`");
      const body = framesToShowLeds(f).split("\n").map(l=>"            "+l).join("\n");
      lines.push(body);
      lines.push(`            `+"`)");
      lines.push(`        basic.pause(${pause})`);
    });
    lines.push(`    }`);
  } else if(mode==="repeat4"){
    lines.push(`    for (let i = 0; i < 4; i++) {`);
    anim.frames.forEach(f=>{
      lines.push(`        basic.showLeds(`+"`");
      const body = framesToShowLeds(f).split("\n").map(l=>"            "+l).join("\n");
      lines.push(body);
      lines.push(`            `+"`)");
      lines.push(`        basic.pause(${pause})`);
    });
    lines.push(`    }`);
    lines.push(`    basic.clearScreen()`);
  } else {
    anim.frames.forEach(f=>emitFrame(f));
    lines.push(`    basic.clearScreen()`);
  }
  lines.push(`}`);
  return lines.join("\n");
}
